let LANG="en";
const HOSTLIKE=/^[a-z0-9_-]+(\.[a-z0-9_-]+)+$/i;
const I18N={re:null};
function i18nRegex(){
  if(!I18N.re){const keys=Object.keys(AR_PHRASES).map(k=>k.replace(/[.*+?^${}()|[\]\\]/g,"\\$&"));
    I18N.re=new RegExp("(?<![A-Za-z])("+keys.join("|")+")(?![A-Za-z])","g")}
  return I18N.re;
}
function arabic(text){return LANG==="ar"&&text&&/[A-Za-z]/.test(text)&&!HOSTLIKE.test(text.trim())?text.replace(i18nRegex(),m=>AR_PHRASES[m]||m):text}
function translateNode(root){
  if(LANG!=="ar"||!root)return;
  if(root.nodeType===3){const t=arabic(root.nodeValue);if(t!==root.nodeValue)root.nodeValue=t;return}
  if(root.nodeType!==1||root.closest?.("textarea,input,select,canvas,#legal"))return;
  for(const a of ["title","placeholder","aria-label"]){const v=root.getAttribute?.(a);if(v){const t=arabic(v);if(t!==v)root.setAttribute(a,t)}}
  root.childNodes.forEach(translateNode);
}
const i18nObserver=new MutationObserver(list=>{if(LANG!=="ar")return;
  for(const m of list){if(m.type==="characterData")translateNode(m.target);else m.addedNodes.forEach(translateNode)}});
/* Called with the saved language; switching back to English reloads the page to bring the original text back */
function applyLanguage(){
  const want=(typeof tools!=="undefined"&&tools.settings?.settings?.language)||"en";
  if(want===LANG)return;
  if(LANG==="ar"&&want==="en"){location.reload();return}
  LANG=want; document.documentElement.lang=want; document.documentElement.dir=want==="ar"?"rtl":"ltr";
  translateNode(document.body);
  i18nObserver.observe(document.body,{childList:true,subtree:true,characterData:true});
}
